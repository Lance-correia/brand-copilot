"""Deterministic, dependency-free generator for the contract's JSON Schema subset."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schemas = {p.stem.removesuffix('.schema'): json.loads(p.read_text())
           for p in sorted((ROOT / 'packages/schema').glob('*.schema.json'))}
nodes = dict(schemas)
for schema in schemas.values():
    nodes.update(schema.get('$defs', {}))
py_lines = ['# Generated by scripts/gen_types.sh. Do not edit.',
            'from __future__ import annotations',
            'from typing import Annotated, Any, Literal',
            'from pydantic import BaseModel, ConfigDict, Field, TypeAdapter',
            '', 'class ContractModel(BaseModel):',
            '    model_config = ConfigDict(extra="forbid")', '']
ts_lines = ['// Generated by scripts/gen_types.sh. Do not edit.']
emitted = set()

def reference(value):
    return value.rsplit('/', 1)[-1].removesuffix('.schema.json')

def type_for(schema, name, lang):
    if '$ref' in schema:
        target = reference(schema['$ref'])
        emit(target)
        return target
    if 'oneOf' in schema:
        return ' | '.join(type_for(x, name, lang) for x in schema['oneOf'])
    if 'const' in schema or 'enum' in schema:
        values = schema.get('enum', [schema.get('const')])
        return ('Literal[' + ', '.join(repr(v) for v in values) + ']'
                if lang == 'py' else ' | '.join(json.dumps(v) for v in values))
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(type_for({**schema, 'type': t}, name, lang) for t in kind)
    if kind == 'object':
        if 'properties' not in schema:
            return 'dict[str, Any]' if lang == 'py' else 'Record<string, unknown>'
        if name not in nodes:
            nodes[name] = schema
        emit(name)
        return name
    if kind == 'array':
        item = type_for(schema['items'], name + 'Item', lang)
        if schema.get('minItems') == schema.get('maxItems') and 'minItems' in schema:
            count = schema['minItems']
            return ('tuple[' + ', '.join([item] * count) + ']'
                    if lang == 'py' else '[' + ', '.join([item] * count) + ']')
        return f'list[{item}]' if lang == 'py' else f'Array<{item}>'
    value = {'string': ('str', 'string'), 'integer': ('int', 'number'),
             'number': ('float', 'number'), 'boolean': ('bool', 'boolean'),
             'null': ('None', 'null')}[kind][lang == 'ts']
    if lang == 'py' and kind != 'null':
        constraints = {'minimum': 'ge', 'maximum': 'le', 'exclusiveMinimum': 'gt',
                       'exclusiveMaximum': 'lt', 'pattern': 'pattern',
                       'minLength': 'min_length', 'maxLength': 'max_length'}
        args = [f'{dest}={schema[src]!r}' for src, dest in constraints.items() if src in schema]
        if args:
            value = f'Annotated[{value}, Field({", ".join(args)})]'
    return value

def emit(name):
    if name in emitted:
        return
    emitted.add(name)
    schema = nodes[name]
    if 'oneOf' in schema:
        py = type_for(schema, name, 'py')
        ts = type_for(schema, name, 'ts')
        py_lines.extend([f'{name} = {py}', ''])
        ts_lines.extend([f'export type {name} = {ts};', ''])
    else:
        py = [f'class {name}(ContractModel):']
        ts = [f'export interface {name} {{']
        for key, field in schema['properties'].items():
            nested = name + key[0].upper() + key[1:]
            py_type = type_for(field, nested, 'py')
            ts_type = type_for(field, nested, 'ts')
            optional = key not in schema.get('required', [])
            py.append(f'    {key}: {py_type}' + (' | None = None' if optional else ''))
            ts.append(f'  {key}{"?" if optional else ""}: {ts_type};')
        py_lines.extend(py + [''])
        ts_lines.extend(ts + ['}', ''])

for name in list(nodes):
    emit(name)
py_lines.append('EDIT_OP_ADAPTER = TypeAdapter(EditOp)')
py_lines.append('LAYER_ADAPTER = TypeAdapter(Layer)')
api = ROOT / 'apps/api/app/schema'
web = ROOT / 'apps/web/src/types'
api.mkdir(parents=True, exist_ok=True)
web.mkdir(parents=True, exist_ok=True)
(api / 'models.py').write_text('\n'.join(py_lines) + '\n')
(api / '__init__.py').write_text('# Generated by scripts/gen_types.sh. Do not edit.\nfrom .models import *  # noqa: F403\n')
(web / 'index.ts').write_text('\n'.join(ts_lines) + '\n')
(web / 'schemas.ts').write_text('// Generated by scripts/gen_types.sh. Do not edit.\nexport const schemas = ' + json.dumps(list(schemas.values()), indent=2) + ' as const;\n')
print(f'Generated {len(schemas)} contracts for TypeScript and Pydantic')
